import type {
  AlwaysAskClass,
  BrowserActionClass,
  BrowserActionTarget,
  CredentialFieldHint,
} from "./commit-classifier.ts";
import type { CaseDirection } from "./paths.cases.ts";

export interface BrowserActionCase {
  readonly id: string;
  readonly direction: CaseDirection;
  readonly target: BrowserActionTarget;
  readonly field?: CredentialFieldHint;
  readonly expected: BrowserActionClass;
  readonly always_ask: AlwaysAskClass | null;
}

const PAGE = "https://shop.example.com/page";

function make(
  id: string,
  target: Omit<BrowserActionTarget, "page_url">,
  expected: BrowserActionClass,
  always_ask: AlwaysAskClass | null = null,
  field?: CredentialFieldHint,
): BrowserActionCase {
  return {
    id,
    direction: expected === "commit" || always_ask !== null ? "over_permission" : "needless_ask",
    target: { page_url: PAGE, ...target },
    expected,
    always_ask,
    ...(field === undefined ? {} : { field }),
  };
}

function button(
  id: string,
  name: string,
  expected: BrowserActionClass,
  always_ask: AlwaysAskClass | null = null,
  extra: Partial<BrowserActionTarget> = {},
): BrowserActionCase {
  return make(id, { action: "click", role: "button", name, ...extra }, expected, always_ask);
}

