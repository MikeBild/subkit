function shortcut(os: DeviceOs, keys: string | readonly string[], blocked: boolean): ShortcutCase {
  const label = typeof keys === "string" ? keys : keys.join(" ");
  return {
    id: `${os}-${label}`,
    direction: blocked ? "over_permission" : "needless_ask",
    os,
    keys,
    blocked,
  };
}

