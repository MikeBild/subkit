import type { DeviceOs } from "../device/protocol.ts";
import type { AppAccess, AppCategory } from "./blocked-apps.ts";
import type { CaseDirection } from "./paths.cases.ts";

export interface AppCase {
  readonly id: string;
  readonly direction: CaseDirection;
  readonly os: DeviceOs;
  readonly bundle_id: string | null;
  readonly name: string | null;
  readonly access: AppAccess;
  readonly category: AppCategory | null;
  readonly note?: string;
}

export interface ShortcutCase {
  readonly id: string;
  readonly direction: CaseDirection;
  readonly os: DeviceOs;
  readonly keys: string | readonly string[];
  readonly blocked: boolean;
}

function app(
  os: DeviceOs,
  bundle_id: string | null,
  name: string | null,
  category: AppCategory | null,
): AppCase {
  const access: AppAccess =
    category === null
      ? "full"
      : category === "browser" || category === "code_editor"
        ? "view_only"
        : "blocked";
  return {
    id: `${os}-${bundle_id ?? "-"}-${name ?? "-"}`,
    direction: access === "full" ? "needless_ask" : "over_permission",
    os,
    bundle_id,
    name,
    access,
    category,
  };
}

const mac = (bundle: string, name: string, category: AppCategory | null): AppCase =>
  app("darwin", bundle, name, category);
const win = (exe: string, category: AppCategory | null): AppCase =>
  app("win32", null, exe, category);

