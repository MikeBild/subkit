import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { buildToolAnnotations } from "../capabilities/tool-meta.ts";
import { type McpTestSuite, startMcpTestSuite } from "./setup.ts";

let suite: McpTestSuite;

beforeAll(async () => {
  suite = await startMcpTestSuite("tools-list");
});

afterAll(async () => {
  await suite.cleanup();
});

const TOOL_NAME_PATTERN = /^[a-zA-Z0-9_-]{1,64}$/;

describe("mcp tools/list", () => {
  test("every tool name matches the MCP name pattern ^[a-zA-Z0-9_-]{1,64}$", async () => {
    const client = await suite.connect();
    const result = await client.listTools();
    for (const tool of result.tools) {
      expect(tool.name).toMatch(TOOL_NAME_PATTERN);
    }
  });

  test("exposes workflows with input schemas", async () => {
    await suite.seedWorkflow({
      name: "list probe",
      slug: "list-probe",
      description: "a tiny probe",
      input_schema: {
        type: "object",
        properties: { who: { type: "string" } },
        required: ["who"],
      },
      steps: [
        {
          kind: "transform",
          id: "echo",
          expression: "$input",
        },
      ],
    });

    const client = await suite.connect();
    const result = await client.listTools();
    const names = result.tools.map((t) => t.name);
    expect(names).toContain("wf_list-probe");
    const tool = result.tools.find((t) => t.name === "wf_list-probe");
    // wf_ tools are framed as an executable action wrapping the workflow's own
    // description (see describeWorkflowTool in mcp/capabilities/tools.ts).
    expect(tool?.description).toContain("a tiny probe");
    expect(tool?.description).toContain("Run the saved workflow");
    expect(tool?.inputSchema).toEqual({
      type: "object",
      properties: { who: { type: "string" } },
      required: ["who"],
    });
  });

  // C2 — MCP 2025-11-25 compliance pin: a no-argument wf_<slug> tool MUST
  // expose {type:"object", properties:{}, additionalProperties:false} so
  // strict clients know the tool accepts only an empty call. This matches
  // the closed-world registry tools generated by zod-to-json-schema.
  test("C2: no-argument wf_ tool inputSchema is EMPTY_OBJECT_SCHEMA with additionalProperties:false", async () => {
    await suite.seedWorkflow({
      name: "no args probe",
      slug: "no-args-probe",
      // No input_schema declared → defaults to EMPTY_OBJECT_SCHEMA in catalog.ts
      steps: [{ kind: "transform", id: "noop", expression: "$input" }],
    });
    const client = await suite.connect();
    const result = await client.listTools();
    const tool = result.tools.find((t) => t.name === "wf_no-args-probe");
    expect(tool).toBeDefined();
    expect(tool?.inputSchema).toEqual({
      type: "object",
      properties: {},
      additionalProperties: false,
    });
  });

  // P2 — Wire-shape coverage: all four MCP-standard annotations must be
  // explicit on wf_* tools. Absent hints are treated as unknown by strict
  // clients, which may gate them unnecessarily.
  test("P2: wf_ tool carries all four MCP-standard annotations on the wire", async () => {
    await suite.seedWorkflow({
      name: "annotations probe",
      slug: "annotations-probe",
      steps: [{ kind: "transform", id: "noop", expression: "$input" }],
    });
    const client = await suite.connect();
    const result = await client.listTools();
    const tool = result.tools.find((t) => t.name === "wf_annotations-probe");
    expect(tool).toBeDefined();
    expect(tool?.annotations?.readOnlyHint).toBe(false);
    // wf_* runs can send/commit/overwrite/delete in external systems → MUST be
    // advertised destructive so a trusted client (claude.ai) gates the run for
    // approval. destructiveHint:false here would let a model fire a live run
    // with no human in the loop.
    expect(tool?.annotations?.destructiveHint).toBe(true);
    expect(tool?.annotations?.idempotentHint).toBe(false);
    expect(tool?.annotations?.openWorldHint).toBe(true); // wf_* executes connectors → open world
  });

  test("versioned workflow effects reach the MCP wire without weakening the default", async () => {
    await suite.seedWorkflow({
      name: "read effect probe",
      slug: "read-effect-probe",
      tool_effect: "read",
      steps: [{ kind: "transform", id: "noop", expression: "$input" }],
    });
    await suite.seedWorkflow({
      name: "reversible effect probe",
      slug: "reversible-effect-probe",
      tool_effect: "reversible_write",
      steps: [{ kind: "transform", id: "noop", expression: "$input" }],
    });
    const client = await suite.connect();
    const byName = new Map((await client.listTools()).tools.map((tool) => [tool.name, tool]));
    expect(byName.get("wf_read-effect-probe")?.annotations).toMatchObject({
      readOnlyHint: true,
      destructiveHint: false,
      idempotentHint: true,
    });
    expect(byName.get("wf_reversible-effect-probe")?.annotations).toMatchObject({
      readOnlyHint: false,
      destructiveHint: false,
      idempotentHint: true,
    });
  });

  // P0 (safety) — write/destructive tools must NOT advertise as read-only or
  // assert destructiveHint:false, or claude.ai files them under "always allow".
  test("P0: write tools advertise readOnlyHint:false and never destructiveHint:false", async () => {
    const { plaintext: adminKey } = await suite.issueApiKey(["*", "mcp:admin"]);
    const client = await suite.connectWithApiKey(adminKey);
    const byName = new Map((await client.listTools()).tools.map((t) => [t.name, t]));
    // call_connector + authenticate are tenant_read for visibility but write.
    for (const name of ["call_connector", "authenticate", "run_workflow"]) {
      const a = byName.get(name)?.annotations;
      if (!a) continue; // tool not in this mode's catalog — skip, don't false-pass
      expect(a.readOnlyHint).toBe(false);
      expect(a.destructiveHint).toBe(true);
    }
    // Title-cased display name (P2a): no raw snake_case in the UI.
    const cc = byName.get("call_connector");
    if (cc) {
      expect(cc.title).not.toContain("_");
      expect(cc.title).not.toBe(cc.name);
    }
  });

  // MCP writes execute directly (no server-side confirm gate) — the client's
  // native `destructiveHint` dialog is the ONLY human gate left, so it must
  // fire for `probe_connector`: its prod path can POST against the vendor's
  // own surface (tool-policies.ts escalates a prod probe to
  // confirm_before_execution). If it ever advertised `readOnlyHint:true` or
  // `destructiveHint:false`, a trusted client would file it under "always
  // allow" and a model could fire a live prod write with no human in the loop.
  test("probe_connector advertises readOnlyHint:false + destructiveHint:true", async () => {
    const { plaintext: adminKey } = await suite.issueApiKey(["*", "mcp:admin"]);
    const client = await suite.connectWithApiKey(adminKey);
    const byName = new Map((await client.listTools()).tools.map((t) => [t.name, t]));
    const tool = byName.get("probe_connector");
    expect(tool).toBeDefined();
    expect(tool?.annotations?.readOnlyHint).toBe(false);
    expect(tool?.annotations?.destructiveHint).toBe(true);
  });

  // probe_connector_draft is `draft_write` — it never appears in a live MCP
  // `tools/list` (draft_write tools are omitted from the MCP catalog and
  // rejected with `not_available_on_surface` on `tools/call`; see
  // `tools/policy.ts` and `tools/providers/conversation.ts`). So its
  // destructiveHint contract is pinned directly against the shared
  // annotation builder (`mcp/capabilities/tool-meta.ts`) instead of a live
  // fetch — this is what every OTHER surface that ever rendered this
  // descriptor would see, and what would fire the day it stops being
  // draft_write-gated off MCP.
  test("probe_connector_draft's annotation builder output stays readOnlyHint:false + destructiveHint:true", () => {
    const annotations = buildToolAnnotations("draft_write", "probe_connector_draft");
    expect(annotations.readOnlyHint).toBe(false);
    expect(annotations.destructiveHint).toBe(true);
  });

  // P2 — execution.taskSupport: conversation_* tools support async Tasks
  // (SEP-1686); wf_* tools run inline only. Strict clients read this to
  // decide which call pattern to use.
  //
  // Conversation tools only appear when the MCP session is in "admin" or
  // "authoring" mode. A ["*"] wildcard key resolves to "authoring" (no
  // narrowing — see mode-resolver.ts), which already shows them; this key
  // ALSO carries mcp:admin so the test runs in admin mode and covers the
  // widest catalog.
  test("P2: conversation_* tools have taskSupport=optional; wf_* tools have taskSupport=forbidden", async () => {
    await suite.seedWorkflow({
      name: "task support probe",
      slug: "task-support-probe",
      steps: [{ kind: "transform", id: "noop", expression: "$input" }],
    });
    // A key that includes mcp:admin puts the MCP session into "admin" mode
    // which enables showConversationTools.
    const { plaintext: adminKey } = await suite.issueApiKey(["*", "mcp:admin"]);
    const client = await suite.connectWithApiKey(adminKey);
    const result = await client.listTools();
    const convTool = result.tools.find((t) => t.name === "conversation_start");
    const wfTool = result.tools.find((t) => t.name === "wf_task-support-probe");
    expect(convTool).toBeDefined();
    expect(wfTool).toBeDefined();
    // Type-cast: Tool.execution is not yet in the base SDK type.
    expect(
      (convTool as Record<string, unknown> & { execution?: { taskSupport?: string } })?.execution
        ?.taskSupport,
    ).toBe("optional");
    expect(
      (wfTool as Record<string, unknown> & { execution?: { taskSupport?: string } })?.execution
        ?.taskSupport,
    ).toBe("forbidden");
  });

  // P2 — outputSchema round-trip: a workflow that declares output_schema MUST
  // echo it in tools/list so strict clients can validate structuredContent.
  test("P2: wf_ tool with declared output_schema echoes it in tools/list", async () => {
    const OUTPUT_SCHEMA = {
      type: "object" as const,
      properties: { score: { type: "number" } },
    };
    await suite.seedWorkflow({
      name: "output schema echo",
      slug: "output-schema-echo",
      output_schema: OUTPUT_SCHEMA,
      steps: [
        {
          kind: "transform",
          id: "out",
          expression: "return { score: 1 };",
          language: "javascript",
        },
      ],
    });
    const client = await suite.connect();
    const result = await client.listTools();
    const tool = result.tools.find((t) => t.name === "wf_output-schema-echo");
    expect(tool).toBeDefined();
    // outputSchema is echoed; type-cast since the base ToolSchema may not expose it.
    const echoed = (tool as Record<string, unknown>)?.outputSchema as { type?: string } | undefined;
    expect(echoed?.type).toBe("object");
  });

  // Regression guard for the catalog-trim reversal: the engine used to trim
  // authoring `tools/list` to fit a schema-token budget and ship a `find_tool`
  // meta-tool as the search-first bridge to the trimmed-out long tail. That
  // trim is gone — strict clients (claude.ai, ChatGPT) proved they defer-load
  // large catalogs natively (an 80-tool probe with a deep canary was both
  // discovered and called), so the engine now advertises the FULL authoring
  // catalog and lets the client's own tool-search handle size. This drives the
  // assertion through the REAL MCP tools/list handler with an
  // authoring-scoped principal — not the pure `assembleCatalog` unit path.
  test("authoring mode advertises the previously-trimmed long tail by name", async () => {
    const { plaintext: authoringKey } = await suite.issueApiKey(["*", "mcp:authoring"]);
    const client = await suite.connectWithApiKey(authoringKey);
    const result = await client.listTools();
    const names = new Set(result.tools.map((t) => t.name));
    expect(names.has("call_connector")).toBe(true);
    expect(names.has("dry_run_transform")).toBe(true);
    expect(names.has("list_skills")).toBe(true);
    // At least one inventory-read tool from the long tail.
    expect(names.has("list_knowledge_sources")).toBe(true);
    // find_tool itself is gone — the search-first bridge is no longer needed
    // because everything it used to bridge to is now advertised directly.
    expect(names.has("find_tool")).toBe(false);
  });

  test("rejects malformed cursors", async () => {
    for (let i = 0; i < 101; i++) {
      await suite.seedWorkflow({
        name: `Paged Tool ${i}`,
        slug: `paged-tool-${i}`,
        steps: [],
      });
    }

    const client = await suite.connect();
    await expect(client.listTools({ cursor: "not-base64-json" })).rejects.toThrow(
      /Invalid pagination cursor for tools\/list/,
    );
  });
});
