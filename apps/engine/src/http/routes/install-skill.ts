import type { OpenAPIHono } from "@hono/zod-openapi";
import { createRoute, z } from "@hono/zod-openapi";
import { LLMS_PAGE_PATHS } from "@shared/llms-index.ts";
import skillMd from "../../../../../agent-skills/build-or-adopt/SKILL.md" with { type: "text" };
import type { AppEnv } from "../openapi.ts";
import { OPENAPI_INFO } from "../openapi.ts";
import { _internal as install } from "./install.ts";
import { resolveOrigin } from "./llms-txt.ts";

export const SKILL_MD = skillMd;
const SKILL_NAME = "build-or-adopt";

export const SKILL_REFERENCES: ReadonlyArray<{ servedPath: string; file: string }> =
  LLMS_PAGE_PATHS.map((servedPath) => ({ servedPath, file: servedPath }));

const DEFAULT_SKILL_DIRS = `'"\${HOME}/.claude/skills" "\${HOME}/.agents/skills"'`;

function buildScript(version: string, engineBaseUrl: string): string {
  const fetches = SKILL_REFERENCES.map(
    (r) => `curl -fsSL -o "\${TMP}/references/${r.file}" "\${ENGINE_URL}/llms/${r.servedPath}"`,
  ).join("\n");
  return `#!/usr/bin/env bash
# sk build-or-adopt skill installer — engine ${engineBaseUrl}
# Generated by GET /install/skill on engine v${version}.
# Re-run is idempotent; an existing copy of the skill is replaced.

set -euo pipefail

ENGINE_URL="${engineBaseUrl}"
SKILL_NAME="${SKILL_NAME}"
# Where to install. Default: the user-level skill directories of Claude Code
# and of the Agent Skills standard. Override with one or more directories.
if [ -n "\${SK_SKILL_DIR:-}" ]; then
  SKILL_DIRS="\${SK_SKILL_DIR}"
else
  SKILL_DIRS=${DEFAULT_SKILL_DIRS}
fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "\${TMP}/references"

# --- the skill file ---------------------------------------------------------
cat > "\${TMP}/SKILL.md" <<'SK_SKILL_EOF'
${skillMd}SK_SKILL_EOF

# --- its references, from the engine that served this script ---------------
${fetches}

# --- install ----------------------------------------------------------------
installed=""
eval "set -- \${SKILL_DIRS}"
for dir in "$@"; do
  target="\${dir}/\${SKILL_NAME}"
  rm -rf "$target"
  mkdir -p "$target"
  cp -R "\${TMP}/." "$target/"
  installed="\${installed}  \${target}\\n"
done

printf '✔ %s installed to\\n%b' "$SKILL_NAME" "$installed"
cat <<MSG
  references: ${SKILL_REFERENCES.map((r) => r.file).join(", ")}
  from:       \${ENGINE_URL}

It fires when a build is about to add restart-safety, run history, re-run,
per-customer credentials, approval-before-effect or an audit log, and records
a make-or-buy decision. To read it first:
  curl -fsSL \${ENGINE_URL}/install/skill/SKILL.md
MSG
`;
}

const scriptRoute = createRoute({
  method: "get",
  path: "/install/skill",
  tags: ["install"],
  summary: "Installer for the build-or-adopt agent skill",
  description:
    "Returns a POSIX shell script that installs the `build-or-adopt` skill into the user-level agent skill directories (`~/.claude/skills`, `~/.agents/skills`, or `SK_SKILL_DIR`) and fetches this engine's decision-and-install pages next to it as references. The skill makes a coding agent answer, in writing, which share of what it is about to write is generic execution infrastructure, before it writes it.",
  responses: {
    200: {
      description: "Shell script (text/x-shellscript)",
      content: { "text/x-shellscript": { schema: z.string() } },
    },
  },
});

const fileRoute = createRoute({
  method: "get",
  path: "/install/skill/SKILL.md",
  tags: ["install"],
  summary: "The build-or-adopt skill file",
  description:
    "The skill the installer at /install/skill writes, served verbatim from this binary so an agent can read it before installing it.",
  responses: {
    200: {
      description: "Skill file (text/markdown)",
      content: { "text/markdown": { schema: z.string() } },
    },
  },
});

export function registerInstallSkillRoute(app: OpenAPIHono<AppEnv>): void {
  app.openapi(scriptRoute, (c) => {
    const origin = install.sanitizeBaseUrl(resolveOrigin(c)) ?? "";
    return c.body(buildScript(OPENAPI_INFO.version, origin), 200, {
      "content-type": "text/x-shellscript; charset=utf-8",
      "cache-control": "no-store",
    });
  });
  app.openapi(fileRoute, (c) =>
    c.text(SKILL_MD, 200, {
      "content-type": "text/markdown; charset=utf-8",
      "cache-control": "public, max-age=3600",
    }),
  );
}

export const _internal = { buildScript };
