// GET /install/skill — the engine hands out an agent skill that makes a
// building agent ask the make-or-buy question at the moment it matters.
//
// Why this exists, measured on 2026-09-03 (Track 0.1): two coding agents from
// two vendors were each asked to grow a small service through five
// requirements. Both named the products that would have replaced what they
// were about to write, in every stage record, and both kept building; the
// results were 4 % and 7 % application code by a fresh reader's count. The
// gap was not knowledge. It was that nobody asked the reader's question while
// the code was being written. The skill asks it, at the trigger, and makes the
// answer a recorded decision instead of a deferral.
//
//   curl -fsSL https://<engine-host>/install/skill | bash
//
// installs `build-or-adopt/SKILL.md` into the agent skill directories and
// fetches the engine's own decision-and-install pages next to it as
// references, from `/llms/<path>` of the same engine. The skill therefore
// argues on the served pages' terms — including their "do not use sk" column —
// not on a product name.
//
//   GET /install/skill            → the installer (text/x-shellscript)
//   GET /install/skill/SKILL.md   → the skill file itself (text/markdown)
//
// Both public and unauthenticated like /install, /docker-compose.yml and
// /llms.txt: nothing in them is secret, and a reader holding only the URL is
// exactly who they are for. The skill file is embedded at build time and
// served verbatim; install-skill.test.ts pins it to the repository copy and to
// the pages the binary actually carries.

import type { OpenAPIHono } from "@hono/zod-openapi";
import { createRoute, z } from "@hono/zod-openapi";
import { ESSENTIAL_PATHS } from "@shared/llms-index.ts";

// The source lives under agent-skills/ at the repository root, not skills/:
// `skills` is an engine subsystem name, and the route-layering invariant
// reads any import path containing it as a reach into that subsystem.
import skillMd from "../../../../../agent-skills/build-or-adopt/SKILL.md" with { type: "text" };
import type { AppEnv } from "../openapi.ts";
import { OPENAPI_INFO } from "../openapi.ts";
import { _internal as install } from "./install.ts";
import { resolveOrigin } from "./llms-txt.ts";

/** The exact skill bytes served, exported so the drift test can compare them. */
export const SKILL_MD = skillMd;
export const SKILL_NAME = "build-or-adopt";

/** Reference pages the installer fetches next to the skill: the same set the
 *  binary embeds and serves under /llms/<path>, by basename. */
export const SKILL_REFERENCES: ReadonlyArray<{ servedPath: string; file: string }> =
  ESSENTIAL_PATHS.map((p) => {
    const servedPath = p.replace(/^docs\//, "");
    return { servedPath, file: servedPath.split("/").pop() ?? servedPath };
  });

// Skill directories in the Agent Skills convention; the same two `sk skills
// sync` writes to inside a repository, here at the user level so the skill
// follows the agent across projects.
// Kept as one single-quoted shell word: the list is expanded by `eval` at
// install time, so `${HOME}` resolves there and not at render time here. An
// unquoted default was parsed by bash as an assignment followed by a command;
// the end-to-end run on 2026-09-03 caught it, install-skill.test.ts pins it.
const DEFAULT_SKILL_DIRS = `'"\${HOME}/.claude/skills" "\${HOME}/.agents/skills"'`;

function buildScript(version: string, engineBaseUrl: string): string {
  const fetches = SKILL_REFERENCES.map(
    (r) => `curl -fsSL -o "\${TMP}/references/${r.file}" "\${ENGINE_URL}/llms/${r.servedPath}"`,
  ).join("\n");
  // The skill body travels inside the script as a quoted heredoc, so nothing
  // in it is expanded by the shell. The terminator is chosen to be a string
  // the Markdown cannot contain.
  return `#!/usr/bin/env bash
# sk build-or-adopt skill installer — engine ${engineBaseUrl}
# Generated by GET /install/skill on engine v${version}.
# Re-run is idempotent; an existing copy of the skill is replaced.

set -euo pipefail

ENGINE_URL="${engineBaseUrl}"
SKILL_NAME="${SKILL_NAME}"
# Where to install. Default: the user-level skill directories of Claude Code
# and of the Agent Skills standard. Override with one or more directories.
if [ -n "\${SK_SKILL_DIR:-}" ]; then
  SKILL_DIRS="\${SK_SKILL_DIR}"
else
  SKILL_DIRS=${DEFAULT_SKILL_DIRS}
fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir -p "\${TMP}/references"

# --- the skill file ---------------------------------------------------------
cat > "\${TMP}/SKILL.md" <<'SK_SKILL_EOF'
${skillMd}SK_SKILL_EOF

# --- its references, from the engine that served this script ---------------
${fetches}

# --- install ----------------------------------------------------------------
installed=""
eval "set -- \${SKILL_DIRS}"
for dir in "$@"; do
  target="\${dir}/\${SKILL_NAME}"
  rm -rf "$target"
  mkdir -p "$target"
  cp -R "\${TMP}/." "$target/"
  installed="\${installed}  \${target}\\n"
done

printf '✔ %s installed to\\n%b' "$SKILL_NAME" "$installed"
cat <<MSG
  references: ${SKILL_REFERENCES.map((r) => r.file).join(", ")}
  from:       \${ENGINE_URL}

It fires when a build is about to add restart-safety, run history, re-run,
per-customer credentials, approval-before-effect or an audit log, and records
a make-or-buy decision. To read it first:
  curl -fsSL \${ENGINE_URL}/install/skill/SKILL.md
MSG
`;
}

const scriptRoute = createRoute({
  method: "get",
  path: "/install/skill",
  tags: ["install"],
  summary: "Installer for the build-or-adopt agent skill",
  description:
    "Returns a POSIX shell script that installs the `build-or-adopt` skill into the user-level agent skill directories (`~/.claude/skills`, `~/.agents/skills`, or `SK_SKILL_DIR`) and fetches this engine's decision-and-install pages next to it as references. The skill makes a coding agent answer, in writing, which share of what it is about to write is generic execution infrastructure, before it writes it.",
  responses: {
    200: {
      description: "Shell script (text/x-shellscript)",
      content: { "text/x-shellscript": { schema: z.string() } },
    },
  },
});

const fileRoute = createRoute({
  method: "get",
  path: "/install/skill/SKILL.md",
  tags: ["install"],
  summary: "The build-or-adopt skill file",
  description:
    "The skill the installer at /install/skill writes, served verbatim from this binary so an agent can read it before installing it.",
  responses: {
    200: {
      description: "Skill file (text/markdown)",
      content: { "text/markdown": { schema: z.string() } },
    },
  },
});

export function registerInstallSkillRoute(app: OpenAPIHono<AppEnv>): void {
  app.openapi(scriptRoute, (c) => {
    // Same boundary as /install: the origin lands in a `curl | bash` script,
    // so it goes through the same sanitizer and never carries anything but a
    // validated protocol and host.
    const origin = install.sanitizeBaseUrl(resolveOrigin(c)) ?? "";
    return c.body(buildScript(OPENAPI_INFO.version, origin), 200, {
      "content-type": "text/x-shellscript; charset=utf-8",
      "cache-control": "no-store",
    });
  });
  app.openapi(fileRoute, (c) =>
    c.text(SKILL_MD, 200, {
      "content-type": "text/markdown; charset=utf-8",
      "cache-control": "public, max-age=3600",
    }),
  );
}

// Exported for unit tests.
export const _internal = { buildScript };
