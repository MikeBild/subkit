// GET /install — public install-script endpoint (Tailscale/Coder pattern).
//
// An operator who has the engine URL but no `sk` binary runs:
//
//   curl -sSL https://my-engine.example.com/install | bash
//
// and ends up with a working `sk` configured to talk back to that engine.
// The script auto-detects platform/arch, downloads the matching release
// binary from the GitHub Release for the engine's running version, and
// optionally writes the engine URL into the resolved profile.
//
// This is deliberately minimal in v3.0.0:
//   - We point at the public GitHub Release for download. Bundling the
//     binaries inside the engine docker image is tracked separately
//     (see plan §P0.7.e); for now the script fetches from
//     github.com/MikeBild/subkit/releases/download/subkit-v<VERSION>/.
//   - SHA-verification piggybacks on the SHA256SUMS file already
//     attached to every release.
//
// The route is unauthenticated by design — the install script itself
// contains no secrets, only public URLs. Operators who want auth-gated
// distribution should run a proxy or pre-share API keys out-of-band.

import type { OpenAPIHono } from "@hono/zod-openapi";
import { createRoute, z } from "@hono/zod-openapi";
import type { AppEnv } from "../openapi.ts";
import { OPENAPI_INFO } from "../openapi.ts";

const route = createRoute({
  method: "get",
  path: "/install",
  tags: ["install"],
  summary: "Public sk install script",
  description:
    "Returns a POSIX shell script that detects platform/arch, fetches the matching `sk` binary from the GitHub Release for the engine's current version, verifies SHA256, and installs to ~/.subkit/bin/sk.",
  responses: {
    200: {
      description: "Shell script (text/x-shellscript)",
      content: {
        "text/x-shellscript": { schema: z.string() },
      },
    },
  },
});

const REPO = "MikeBild/subkit";

function buildScript(version: string, engineBaseUrl: string): string {
  // Heredoc-style; escape only what bash would interpret. Single quotes
  // are intentional inside the script so $VARS are expanded by bash at
  // run time, not by us at template-render time.
  return `#!/usr/bin/env bash
# subkit sk installer — engine ${engineBaseUrl}
# Generated by GET /install on engine v${version}.
# Re-run is idempotent; existing binary is overwritten.

set -euo pipefail

VERSION="${version}"
REPO="${REPO}"
ENGINE_URL="${engineBaseUrl}"
INSTALL_DIR="\${SK_INSTALL_DIR:-\${HOME}/.subkit/bin}"

# --- platform detection -----------------------------------------------------
uname_s=$(uname -s)
uname_m=$(uname -m)
case "$uname_s" in
  Darwin) os=darwin ;;
  Linux)  os=linux ;;
  *) echo "unsupported OS: $uname_s" >&2; exit 1 ;;
esac
case "$uname_m" in
  arm64|aarch64) arch=arm64 ;;
  x86_64|amd64)  arch=x64 ;;
  *) echo "unsupported arch: $uname_m" >&2; exit 1 ;;
esac

ASSET="sk_\${os}_\${arch}"
RELEASE_BASE="https://github.com/\${REPO}/releases/download/subkit-v\${VERSION}"
ASSET_URL="\${RELEASE_BASE}/\${ASSET}"
SUMS_URL="\${RELEASE_BASE}/SHA256SUMS"

# --- download ---------------------------------------------------------------
mkdir -p "$INSTALL_DIR"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

echo "fetching $ASSET from $RELEASE_BASE"
curl -fsSL -o "\${TMP}/\${ASSET}" "$ASSET_URL"
curl -fsSL -o "\${TMP}/SHA256SUMS" "$SUMS_URL"

# --- verify -----------------------------------------------------------------
expected=$(grep " \${ASSET}$" "\${TMP}/SHA256SUMS" | awk '{print $1}')
if [ -z "$expected" ]; then
  echo "no SHA entry for \${ASSET} in SHA256SUMS — refusing to install" >&2
  exit 1
fi
if command -v sha256sum >/dev/null; then
  actual=$(sha256sum "\${TMP}/\${ASSET}" | awk '{print $1}')
elif command -v shasum >/dev/null; then
  actual=$(shasum -a 256 "\${TMP}/\${ASSET}" | awk '{print $1}')
else
  echo "no sha256sum / shasum on PATH — refusing to install" >&2
  exit 1
fi
if [ "$actual" != "$expected" ]; then
  echo "SHA256 mismatch — refusing to install" >&2
  echo "  expected: $expected" >&2
  echo "  actual:   $actual" >&2
  exit 1
fi

# --- install ----------------------------------------------------------------
chmod +x "\${TMP}/\${ASSET}"
mv "\${TMP}/\${ASSET}" "\${INSTALL_DIR}/sk"

cat <<MSG
✔ sk installed to \${INSTALL_DIR}/sk
  version: \${VERSION}
  engine:  \${ENGINE_URL}

Next:
  export PATH="\${INSTALL_DIR}:$PATH"
  # First boot: redeem the bootstrap token from engine stdout.
  sk init --engine-url \${ENGINE_URL}
  # Already-bootstrapped engine: log in with an existing API key.
  sk login --engine-url \${ENGINE_URL} --api-key <your-api-key>
  sk doctor
MSG
`;
}

export function registerInstallRoute(app: OpenAPIHono<AppEnv>): void {
  app.openapi(route, async (c) => {
    // Resolve the engine's public URL: prefer the explicit
    // X-Forwarded-Host / Host headers (so reverse-proxied deployments
    // get the right thing), then fall back to PUBLIC_BASE_URL env, then
    // to the request URL itself.
    const fwdProto = c.req.header("x-forwarded-proto");
    const fwdHost = c.req.header("x-forwarded-host") ?? c.req.header("host");
    const envBase = process.env.PUBLIC_BASE_URL;
    const reqUrl = new URL(c.req.url);
    const engineBaseUrl =
      envBase?.replace(/\/$/, "") ??
      (fwdHost ? `${fwdProto ?? reqUrl.protocol.replace(/:$/, "")}://${fwdHost}` : reqUrl.origin);
    const body = buildScript(OPENAPI_INFO.version, engineBaseUrl);
    return c.body(body, 200, {
      "content-type": "text/x-shellscript; charset=utf-8",
      "cache-control": "no-store",
    });
  });
}

