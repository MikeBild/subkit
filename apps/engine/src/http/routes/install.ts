import type { OpenAPIHono } from "@hono/zod-openapi";
import { createRoute, z } from "@hono/zod-openapi";
import type { AppEnv } from "../openapi.ts";
import { OPENAPI_INFO } from "../openapi.ts";

const route = createRoute({
  method: "get",
  path: "/install",
  tags: ["install"],
  summary: "Public sk install script",
  description:
    "Returns a POSIX shell script that detects platform/arch, fetches the matching `sk` binary and license notices from the engine bundle or an explicit mirror, verifies SHA256, and installs to ~/.subkit/bin.",
  responses: {
    200: {
      description: "Shell script (text/x-shellscript)",
      content: {
        "text/x-shellscript": { schema: z.string() },
      },
    },
  },
});

function buildScript(version: string, engineBaseUrl: string): string {
  return `#!/usr/bin/env bash
# subkit sk installer — engine ${engineBaseUrl}
# Generated by GET /install on engine v${version}.
# Re-run is idempotent; existing binary is overwritten.

set -euo pipefail

VERSION="${version}"
ENGINE_URL="${engineBaseUrl}"
INSTALL_DIR="\${SK_INSTALL_DIR:-\${HOME}/.subkit/bin}"
# Optional mirror for deployments whose engine image does not bundle the CLI.
# Must serve sk_<os>_<arch> and a SHA256SUMS listing it.
MIRROR_BASE="\${SK_INSTALL_BASE_URL:-}"

# --- platform detection -----------------------------------------------------
uname_s=$(uname -s)
uname_m=$(uname -m)
case "$uname_s" in
  Darwin) os=darwin ;;
  Linux)  os=linux ;;
  *) echo "unsupported OS: $uname_s" >&2; exit 1 ;;
esac
case "$uname_m" in
  arm64|aarch64) arch=arm64 ;;
  x86_64|amd64)  arch=x64 ;;
  *) echo "unsupported arch: $uname_m" >&2; exit 1 ;;
esac

ASSET="sk_\${os}_\${arch}"
BUNDLED_ASSET_URL="\${ENGINE_URL}/install/sk-\${os}-\${arch}"
BUNDLED_SUMS_URL="\${ENGINE_URL}/install/sha256sums"

# --- pick source ------------------------------------------------------------
# The engine first: the application-complete image serves the matching binary
# itself, which is the only path that works with no outbound egress.
if curl -fsSI --max-time 5 -o /dev/null "$BUNDLED_ASSET_URL" 2>/dev/null; then
  ASSET_URL="$BUNDLED_ASSET_URL"
  SUMS_URL="$BUNDLED_SUMS_URL"
  NOTICE_BASE="\${ENGINE_URL}/install"
  SOURCE="engine ($ENGINE_URL)"
elif [ -n "$MIRROR_BASE" ]; then
  ASSET_URL="\${MIRROR_BASE%/}/\${ASSET}"
  SUMS_URL="\${MIRROR_BASE%/}/SHA256SUMS"
  NOTICE_BASE="\${MIRROR_BASE%/}"
  SOURCE="mirror ($MIRROR_BASE)"
else
  cat >&2 <<'NOSOURCE'
This engine does not serve the sk binaries, and no mirror was given.

That is the slim image: it runs the engine but carries no CLI to hand out.
Three ways forward, cheapest first:

  1. Use the application-complete image, which bundles sk and serves it here.
     Its Compose file is one fetch away:
       curl -O ${engineBaseUrl}/docker-compose.yml
  2. Point this installer at a mirror that serves sk_<os>_<arch> next to a
     SHA256SUMS file:
       SK_INSTALL_BASE_URL=https://your-mirror.example.com curl -sSL ${engineBaseUrl}/install | bash
  3. Copy the binary out of a running application-complete engine:
       docker compose cp engine:/usr/local/bin/sk ./sk

Nothing was installed.
NOSOURCE
  exit 1
fi

# --- download ---------------------------------------------------------------
mkdir -p "$INSTALL_DIR"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

echo "fetching $ASSET from $SOURCE"
curl -fsSL -o "\${TMP}/\${ASSET}" "$ASSET_URL"
curl -fsSL -o "\${TMP}/SHA256SUMS" "$SUMS_URL"

# --- verify -----------------------------------------------------------------
for FILE in LICENSE THIRD_PARTY_NOTICES.txt; do
  curl -fsSL -o "\${TMP}/$FILE" "$NOTICE_BASE/$FILE"
done
for FILE in "$ASSET" LICENSE THIRD_PARTY_NOTICES.txt; do
  if [ ! -s "\${TMP}/$FILE" ]; then
    echo "empty asset: $FILE — refusing to install" >&2
    exit 1
  fi
  expected=$(awk -v asset="$FILE" '$2 == asset {print $1}' "\${TMP}/SHA256SUMS")
  if [[ ! "$expected" =~ ^[a-fA-F0-9]{64}$ ]]; then
    echo "missing, duplicate or invalid SHA entry for $FILE — refusing to install" >&2
    exit 1
  fi
  if command -v sha256sum >/dev/null; then
    actual=$(sha256sum "\${TMP}/$FILE" | awk '{print $1}')
  elif command -v shasum >/dev/null; then
    actual=$(shasum -a 256 "\${TMP}/$FILE" | awk '{print $1}')
  else
    echo "no sha256sum / shasum on PATH — refusing to install" >&2
    exit 1
  fi
  if [ "$actual" != "$expected" ]; then
    echo "SHA256 mismatch — refusing to install" >&2
    exit 1
  fi
  if [ -d "\${INSTALL_DIR}/subkit.$FILE" ] || [ -d "\${INSTALL_DIR}/sk" ]; then
    echo "installation target is a directory — refusing to install" >&2
    exit 1
  fi
done

# --- install ----------------------------------------------------------------
for FILE in LICENSE THIRD_PARTY_NOTICES.txt; do
  chmod 644 "\${TMP}/$FILE"
  mv -f "\${TMP}/$FILE" "\${INSTALL_DIR}/subkit.$FILE"
done
chmod +x "\${TMP}/\${ASSET}"
mv "\${TMP}/\${ASSET}" "\${INSTALL_DIR}/sk"

cat <<MSG
✔ sk installed to \${INSTALL_DIR}/sk
  version: \${VERSION}
  engine:  \${ENGINE_URL}

Next:
  export PATH="\${INSTALL_DIR}:$PATH"
  # First boot: redeem the one-time bootstrap token from engine stdout.
  # The engine prints it once on first start; copy the value next to
  # 'sk init --token …' in the banner.
  sk init --engine-url \${ENGINE_URL} --token <bootstrap-token>
  # Already-bootstrapped engine: log in with an existing API key.
  sk login --engine-url \${ENGINE_URL} --api-key <your-api-key>
  sk doctor
MSG
`;
}

const SAFE_HOST = /^[a-zA-Z0-9.-]+(:\d{1,5})?$/;
const SAFE_IPV6_HOST = /^\[[0-9a-fA-F:]+\](:\d{1,5})?$/;

function sanitizeBaseUrl(candidate: string): string | null {
  let u: URL;
  try {
    u = new URL(candidate);
  } catch {
    return null;
  }
  if (u.protocol !== "http:" && u.protocol !== "https:") return null;
  const host = u.host;
  if (!SAFE_HOST.test(host) && !SAFE_IPV6_HOST.test(host)) return null;
  return `${u.protocol}//${host}`;
}

export function registerInstallRoute(app: OpenAPIHono<AppEnv>): void {
  app.openapi(route, async (c) => {
    let configBase = "";
    try {
      const { getConfig } = await import("../../config/loader.ts");
      configBase = getConfig().server.public_base_url ?? "";
    } catch {}
    const reqUrl = new URL(c.req.url);

    const candidates: string[] = [];
    if (configBase) candidates.push(configBase);
    const fwdHost = c.req.header("x-forwarded-host") ?? c.req.header("host");
    if (fwdHost) {
      const proto = c.req.header("x-forwarded-proto") ?? reqUrl.protocol.replace(/:$/, "");
      candidates.push(`${proto}://${fwdHost}`);
    }
    candidates.push(reqUrl.origin);

    let engineBaseUrl = "";
    for (const candidate of candidates) {
      const safe = sanitizeBaseUrl(candidate);
      if (safe) {
        engineBaseUrl = safe;
        break;
      }
    }
    if (!engineBaseUrl) {
      engineBaseUrl = sanitizeBaseUrl(reqUrl.origin) ?? "";
    }

    const body = buildScript(OPENAPI_INFO.version, engineBaseUrl);
    return c.body(body, 200, {
      "content-type": "text/x-shellscript; charset=utf-8",
      "cache-control": "no-store",
    });
  });
}

export const _internal = { buildScript, sanitizeBaseUrl };
