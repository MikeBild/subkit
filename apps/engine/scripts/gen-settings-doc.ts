import { ConfigSchema, SECTION_ORDER } from "../src/config/schema.ts";
import { type ConfigLeaf, dottedPath, listConfigLeaves } from "../src/config/walk.ts";

function defaultValueFor(leaf: ConfigLeaf): string {
  let cursor: { def?: { type?: string; defaultValue?: unknown; innerType?: unknown } } =
    leaf.schema as never;
  for (let guard = 0; guard < 32; guard += 1) {
    const def = cursor.def;
    if (!def) break;
    if (def.type === "default" && "defaultValue" in def) {
      return JSON.stringify(def.defaultValue);
    }
    if (def.innerType) {
      cursor = def.innerType as typeof cursor;
      continue;
    }
    break;
  }
  return leaf.nullable ? "null" : "—";
}

function leafKindLabel(leaf: ConfigLeaf): string {
  if (leaf.kind === "enum" && leaf.enumValues && leaf.enumValues.length > 0) {
    return `enum(${leaf.enumValues.map((v) => `"${v}"`).join(" \\| ")})`;
  }
  if (leaf.kind === "string-list") return "string[]";
  if (leaf.kind === "string-array") return "array";
  if (leaf.kind === "json") return "json";
  return leaf.kind;
}

function renderSection(section: string, leaves: ConfigLeaf[]): string {
  const description =
    (
      (
        ConfigSchema as {
          def?: { shape?: Record<string, { description?: string; meta?: () => unknown }> };
        }
      ).def?.shape?.[section] as
        | { description?: string; meta?: () => { description?: string } | undefined }
        | undefined
    )?.meta?.()?.description ?? "";

  const sortedLeaves = [...leaves].sort((a, b) => dottedPath(a).localeCompare(dottedPath(b)));

  const rows = sortedLeaves.map((leaf) => {
    const path = dottedPath(leaf);
    const kind = leafKindLabel(leaf);
    const def = defaultValueFor(leaf);
    const scope = leaf.meta.scope ?? "global";
    const sensitive = leaf.meta.secret ? "yes" : "no";
    const requiresRestart = leaf.meta.requiresRestart ? "yes" : "no";
    const desc = (leaf.description ?? "").replace(/\|/g, "\\|");
    return `| \`${path}\` | ${kind} | \`${def}\` | ${scope} | ${sensitive} | ${requiresRestart} | ${desc} |`;
  });

  const header = `## ${section}`;
  const blurb = description ? `\n${description}\n` : "";
  const table = [
    "| path | type | default | scope | sensitive | requiresRestart | description |",
    "| ---- | ---- | ------- | ----- | --------- | --------------- | ----------- |",
    ...rows,
  ].join("\n");
  return `${header}${blurb}\n${table}\n`;
}

function main(): void {
  const all = listConfigLeaves();
  const bySection = new Map<string, ConfigLeaf[]>();
  for (const leaf of all) {
    const head = leaf.path[0] as string;
    const list = bySection.get(head) ?? [];
    list.push(leaf);
    bySection.set(head, list);
  }

  const lines: string[] = [
    "<!-- AUTO-GENERATED by apps/engine/scripts/gen-settings-doc.ts. Do not edit by hand; run `bun run gen llms`. -->",
    "",
    "# SubKit runtime settings",
    "",
    "Look up every runtime setting with its description and default value.",
    "You change a value with `sk settings configure` and `sk settings set`, through the",
    "HTTP or MCP settings APIs, or in the canonical config file. Per-tenant overrides go",
    "into the file's `tenants` section and only apply to settings tagged `scope=tenant`.",
    "",
    "A value resolves in this order: tenant overlay, then global value, then schema",
    "default. Environment variables never set a runtime setting; only the bootstrap-only",
    "process bindings `database.url`, `storage.backend`, `storage.filesystem.root` and",
    "`deployment.mode` (from `SUBKIT_DEPLOYMENT_MODE`) come from the environment at startup.",
    "",
  ];

  for (const section of SECTION_ORDER) {
    const leaves = bySection.get(section);
    if (!leaves || leaves.length === 0) continue;
    lines.push(renderSection(section, leaves));
  }

  lines.push(
    "## Authentication providers",
    "",
    "`auth.providers` is one atomic, validated runtime setting available through Cockpit, HTTP, MCP, `sk settings`, and the canonical config file. Records use `protocol: api_key` or `oidc`; one API-key adapter and multiple named direct OIDC adapters may coexist. Provider ids must be unique, and every OIDC callback is `/v1/identity/login/callback` on `server.public_base_url`. A successful write is active for subsequent browser-login requests without an engine restart.",
    "",
    "OIDC records are public clients using Authorization Code with PKCE. Runtime configuration intentionally has no `client_secret` field and rejects one if supplied; use an issuer that supports public clients with `token_endpoint_auth_method=none`. The environment is not an auth-provider source.",
    "",
    "Configured labels are diagnostic metadata only. The common `mcp-auth` surface derives its two user actions from protocol and always presents `Continue with SSO` before `Continue with API key`. Discovery exposes the canonical labels `SSO` and `API key`; no provider-specific route or parallel configuration tree is accepted.",
    "",
  );

  lines.push(
    "## Filesystem object store",
    "",
    "On a single device, the engine can keep files and offloaded results in a folder instead of an S3-compatible object store. Set two environment variables before the engine starts:",
    "",
    "| Variable | Setting | Value |",
    "| -------- | ------- | ----- |",
    "| `OBJECT_STORAGE_BACKEND` | `storage.backend` | `filesystem` (default `s3`) |",
    "| `OBJECT_STORAGE_ROOT` | `storage.filesystem.root` | absolute folder, for example `<app data>/local/<workspace>/files` |",
    "",
    "Both are bootstrap-only: they come from the environment on every start, a stored revision cannot change them, and the settings APIs refuse to write them. The `storage.object_store` values are not needed in this mode.",
    "",
    "- **Startup check:** the parent folder must exist. The engine creates the folder with mode `0700`, tightens an existing one to `0700`, and proves it can write, read, delete and hard-link inside it. If a check fails, the engine does not start and names the reason (`root_parent_missing`, `root_not_directory`, `root_not_writable`, `root_cross_device`, `root_no_hard_links`) with a remedy.",
    "- **Writes:** each object is written to a staging file, flushed to disk, then linked into place, so a reader sees the whole object or nothing. An existing key is never overwritten. Files get mode `0600`, folders `0700`.",
    "- **Keys:** every key segment is encoded to lowercase ASCII (`a-z`, `0-9`, `.`, `_`, `-`, other bytes as `%xx`), so keys that differ only in case or Unicode form stay apart on case-insensitive disks, and Windows reserved names are safe. `..`, empty segments and absolute keys are refused, and a link that leads outside the folder is never followed.",
    "- **Backup:** the folder is the whole object store; copy it together with the database dump.",
    "- **Not supported:** network drives, cloud-synced folders and disks without hard links, such as exFAT.",
    "",
  );

  process.stdout.write(`${lines.join("\n").trimEnd()}\n`);
}

main();
