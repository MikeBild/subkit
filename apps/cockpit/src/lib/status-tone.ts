/** Tone of a status badge. The table maps the engine's status words; unknown states stay neutral. */
export type BadgeTone = "ok" | "warn" | "error" | "neutral";

const TONES: Partial<Record<string, BadgeTone>> = {
  ok: "ok",
  success: "ok",
  completed: "ok",
  succeeded: "ok",
  enabled: "ok",
  active: "ok",
  approved: "ok",
  applied: "ok",
  ready: "ok",
  clean: "ok",
  committed: "ok",
  valid: "ok",
  verified: "ok",
  failing: "error",
  stopped: "error",
  repair_required: "warn",
  waiting_approval: "warn",
  waiting_connector: "warn",
  failed: "error",
  error: "error",
  expired: "error",
  needs_reauth: "error",
  rejected: "error",
  denied: "error",
  timed_out: "error",
  timeout: "error",
  aborted: "error",
  infected: "error",
  critical: "error",
  unreadable: "error",
  pending: "warn",
  running: "warn",
  queued: "warn",
  waiting_budget: "warn",
  uncertain: "warn",
  processing: "warn",
  uploading: "warn",
  scanning: "warn",
  degraded: "warn",
  needs_attention: "warn",
  needs_update: "warn",
  expiring: "warn",
  awaiting_input: "warn",
  proposed: "warn",
  warn: "warn",
};

export function statusTone(state: string): BadgeTone {
  return TONES[state.toLowerCase()] ?? "neutral";
}
