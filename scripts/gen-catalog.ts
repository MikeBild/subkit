import templates from "../apps/engine/src/connectors/templates.json";

type Recipe = {
  slug: string;
  title: string;
  description?: string;
  tags?: string[];
  required_connectors?: { template: string; role?: string }[];
  deprecated?: boolean;
  workflow?: { trigger?: { kind?: string } };
};

type Template = {
  slug: string;
  name: string;
  driver: string;
  auth_type?: string;
  description?: string;
  category: string;
  recipes?: Recipe[];
};

const CATEGORY_ORDER: readonly string[] = [
  "crm",
  "payments",
  "ecommerce",
  "marketing",
  "communication",
  "project-management",
  "productivity",
  "storage",
  "devops",
  "database",
  "analytics",
  "scraping",
  "enterprise",
  "ai",
  "cloud",
  "aws",
];

const CATEGORY_TITLE: Record<string, string> = {
  crm: "CRM",
  payments: "Payments",
  ecommerce: "E-commerce",
  marketing: "Marketing",
  communication: "Communication",
  "project-management": "Project management",
  productivity: "Productivity & documents",
  storage: "File storage",
  devops: "Dev tools",
  database: "Databases",
  analytics: "Analytics",
  scraping: "Web scraping",
  enterprise: "Enterprise & support",
  ai: "AI",
  cloud: "Cloud",
  aws: "AWS operations",
};

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n/g, " ").trim();
}

function firstSentence(text: string): string {
  const cut = text.indexOf(". ");
  return cut === -1 ? text : text.slice(0, cut + 1);
}

function templateRow(t: Template): string {
  const auth = t.auth_type ?? "none";
  const desc = t.description ? escapeCell(firstSentence(t.description)) : "—";
  return `| **${escapeCell(t.name)}** | \`${t.slug}\` | ${t.driver} | ${auth} | ${desc} |`;
}

function triggerKind(r: Recipe): string {
  return r.workflow?.trigger?.kind ?? "request";
}

function extraConnectors(t: Template, r: Recipe): string {
  const extras = (r.required_connectors ?? [])
    .map((c) => c.template)
    .filter((slug) => slug !== t.slug);
  return extras.length > 0 ? extras.map((s) => `\`${s}\``).join(", ") : "—";
}

function recipeRow(t: Template, r: Recipe): string {
  const what = escapeCell(firstSentence(r.description ?? r.title));
  return `| \`${r.slug}\` | ${what} | ${triggerKind(r)} | ${extraConnectors(t, r)} |`;
}

function main(): void {
  const all = templates as Template[];
  const byCategory = new Map<string, Template[]>();
  for (const t of all) {
    const bucket = byCategory.get(t.category) ?? [];
    bucket.push(t);
    byCategory.set(t.category, bucket);
  }
  const unknown = [...byCategory.keys()].filter((c) => !CATEGORY_ORDER.includes(c)).sort();
  const order = [...CATEGORY_ORDER.filter((c) => byCategory.has(c)), ...unknown];

  const withRecipes = all
    .filter((t) => (t.recipes ?? []).some((r) => !r.deprecated))
    .sort((a, b) => a.slug.localeCompare(b.slug));
  const recipeCount = withRecipes.reduce(
    (n, t) => n + (t.recipes ?? []).filter((r) => !r.deprecated).length,
    0,
  );

  const lines: string[] = [
    "<!-- generated by scripts/gen-catalog.ts — do not edit by hand -->",
    "",
    "# Connector & recipe catalog",
    "",
    "Find the connector templates and recipes that ship with SubKit. " +
      `There are **${all.length} connector templates** in **${order.length} categories**, ` +
      `carrying **${recipeCount} recipes**: complete, runnable workflows you clone ` +
      "instead of starting from a blank page.",
    "",
    "A **template** connects a system: base URL, sign-in flow, endpoint schema and a " +
      "vendor-basics skill. A **recipe** is a complete workflow built on that template. " +
      "Say what you want in a conversation, and SubKit clones the closest recipe as " +
      "your first draft.",
    "",
    "Some recipes ask for a value when you install them, such as a GA4 property id or, for the " +
      "web-scraper recipes, `allowed_hosts`: the host names their url may point to. SubKit writes " +
      "these values into the steps before you approve the workflow, so the approval names them. " +
      "A web-scraper run then fetches only https addresses on exactly those hosts and stops with " +
      "`request_host_not_allowed` for any other address.",
    "",
    "## Connector templates",
    "",
  ];

  for (const category of order) {
    const group = [...(byCategory.get(category) ?? [])].sort((a, b) =>
      a.slug.localeCompare(b.slug),
    );
    lines.push(
      `### ${CATEGORY_TITLE[category] ?? category}`,
      "",
      "| Template | slug | driver | auth | What it connects |",
      "| -------- | ---- | ------ | ---- | ---------------- |",
      ...group.map(templateRow),
      "",
    );
  }

  lines.push(
    "## Recipes",
    "",
    "Grouped by template. **Trigger** is how the workflow starts: `request` (on demand — " +
      "chat, CLI, MCP, REST), `schedule` (cron), or `webhook` (an external system calls in). " +
      "**Also uses** lists connectors beyond the template's own.",
    "",
  );

  for (const t of withRecipes) {
    const recipes = [...(t.recipes ?? [])]
      .filter((r) => !r.deprecated)
      .sort((a, b) => a.slug.localeCompare(b.slug));
    lines.push(
      `### ${escapeCell(t.name)} (\`${t.slug}\`)`,
      "",
      "| Recipe | What it does | Trigger | Also uses |",
      "| ------ | ------------ | ------- | --------- |",
      ...recipes.map((r) => recipeRow(t, r)),
      "",
    );
  }

  process.stdout.write(`${lines.join("\n").trimEnd()}\n`);
}

main();
