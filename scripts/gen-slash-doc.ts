// Generate docs/authors/slash-commands.md from the live SLASH_COMMANDS
// registry in apps/sk/src/slash.ts.
//
// One section per category (in the same order /help renders them),
// each a table of: command, aliases, requires (permission), description.
// Commands are sorted alphabetically within a category so the output is
// byte-stable — no timestamps, no machine-specific paths.
//
// Wired into `bun run gen:slash-doc` (writes the file) and
// `bun run check:slash-doc-drift` (regenerates + git-diff gate).
//
// Usage:
//   bun run scripts/gen-slash-doc.ts > docs/authors/slash-commands.md

import { SLASH_COMMANDS, type SlashCommand } from "../apps/sk/src/slash.ts";

// Mirror the category order used by `renderHelp` in slash.ts so the
// reference reads in the same order as the in-REPL `/help` screen.
const CATEGORY_ORDER: readonly SlashCommand["category"][] = [
  "session",
  "auth",
  "context",
  "mcp",
  "admin",
  "util",
];

const CATEGORY_TITLE: Record<SlashCommand["category"], string> = {
  session: "Session",
  auth: "Auth",
  context: "Context",
  mcp: "MCP",
  admin: "Admin",
  util: "Utility",
};

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|");
}

function renderRow(cmd: SlashCommand): string {
  const name = `\`/${cmd.name}\``;
  const aliases =
    cmd.aliases && cmd.aliases.length > 0 ? cmd.aliases.map((a) => `\`/${a}\``).join(", ") : "—";
  const requires = cmd.requires ? `\`${cmd.requires}\`` : "—";
  const help = escapeCell(cmd.help);
  return `| ${name} | ${aliases} | ${requires} | ${help} |`;
}

function renderSection(category: SlashCommand["category"], commands: SlashCommand[]): string {
  const sorted = [...commands].sort((a, b) => a.name.localeCompare(b.name));
  const rows = sorted.map(renderRow);
  return [
    `## ${CATEGORY_TITLE[category]}`,
    "",
    "| command | aliases | requires | description |",
    "| ------- | ------- | -------- | ----------- |",
    ...rows,
    "",
  ].join("\n");
}

function main(): void {
  const byCategory = new Map<SlashCommand["category"], SlashCommand[]>();
  for (const cmd of SLASH_COMMANDS) {
    const bucket = byCategory.get(cmd.category) ?? [];
    bucket.push(cmd);
    byCategory.set(cmd.category, bucket);
  }

  const lines: string[] = [
    "<!-- generated by scripts/gen-slash-doc.ts — do not edit by hand -->",
    "",
    "# Slash commands",
    "",
    "Slash commands run from the `sk` REPL. Type `/` to open the fuzzy",
    "picker, or `/help` for the persona-filtered cheat sheet. A command",
    "with a `requires` permission is hidden from any persona that cannot",
    "invoke it — the engine still enforces the permission on every call,",
    "so this column is the UX gate, not the security boundary.",
    "",
  ];

  for (const category of CATEGORY_ORDER) {
    const commands = byCategory.get(category);
    if (!commands || commands.length === 0) continue;
    lines.push(renderSection(category, commands));
  }

  process.stdout.write(`${lines.join("\n").trimEnd()}\n`);
}

main();
