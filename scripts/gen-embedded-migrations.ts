#!/usr/bin/env bun
//
// Generate `apps/engine/src/db/migrations/embedded.ts` from the
// drizzle-kit journal (`meta/_journal.json`).
//
// Why: every new migration needs a corresponding `import sqlNNNN ...`
// + `SQL_BY_TAG` entry. A drizzle-kit run produces the .sql file but
// not the manifest, so the manual update is a regression magnet.
// This script regenerates the manifest from the journal
// and is wired into:
//
//   * `bun run db:gen-embedded` — manual regenerate
//   * `bun run check:embedded-drift` — CI gate (fails on uncommitted diff)
//
// Run after every `bun run db:generate`.

import { promises as fs } from "node:fs";
import path from "node:path";

const REPO_ROOT = path.resolve(import.meta.dir, "..");
const MIGRATIONS_DIR = path.join(REPO_ROOT, "apps", "engine", "src", "db", "migrations");
const JOURNAL_PATH = path.join(MIGRATIONS_DIR, "meta", "_journal.json");
const OUT_PATH = path.join(MIGRATIONS_DIR, "embedded.ts");

interface JournalEntry {
  idx: number;
  tag: string;
  when: number;
  breakpoints?: boolean;
}

interface Journal {
  version: string;
  dialect: string;
  entries: JournalEntry[];
}

function ident(tag: string): string {
  // e.g. `0007_webhooks_inbound_origin` → `sql0007WebhooksInboundOrigin`
  // For numeric prefixes the result starts with a letter (`sql`) so
  // it's a valid JS identifier.
  const parts = tag.split("_");
  const head = parts[0] ?? "";
  const rest = parts
    .slice(1)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
  return `sql${head}${rest}`;
}

async function main(): Promise<void> {
  const journalRaw = await fs.readFile(JOURNAL_PATH, "utf8");
  const journal = JSON.parse(journalRaw) as Journal;
  const entries = [...journal.entries].sort((a, b) => a.idx - b.idx);

  const imports = entries
    .map((e) => `import ${ident(e.tag)} from "./${e.tag}.sql" with { type: "text" };`)
    .join("\n");

  const tagMap = entries.map((e) => `  "${e.tag}": ${ident(e.tag)},`).join("\n");

  const out = `// Build-time embedded migration bundle.
//
// **AUTO-GENERATED by \`scripts/gen-embedded-migrations.ts\`.**  Do not
// edit by hand — the codegen rebuilds this file from
// \`meta/_journal.json\` on every \`bun run db:gen-embedded\`. The CI
// drift check (\`bun run check:embedded-drift\`) fails if the
// committed file disagrees with the regenerated output.
//
// We import each migration's raw SQL as text and the journal as JSON.
// \`bun build --compile\` inlines the contents of every imported text /
// JSON asset into the binary, so the runtime never reads the
// filesystem and the engine + migration set ship as a single artifact.
//
// Drift safeguard: \`migrate-embedded-bundle.test.ts\` re-reads the
// on-disk SQL files at test time and asserts every embedded body's
// SHA-256 matches the file. CI fails loudly if a new migration is
// added but not registered here.

import { createHash } from "node:crypto";
${imports}
import journalMeta from "./meta/_journal.json" with { type: "json" };

interface JournalEntry {
  idx: number;
  tag: string;
  when: number;
  breakpoints?: boolean;
}

interface Journal {
  version: string;
  dialect: string;
  entries: JournalEntry[];
}

export interface EmbeddedMigration {
  idx: number;
  tag: string;
  when: number;
  hash: string;
  statements: string[];
}

const SQL_BY_TAG: Record<string, string> = {
${tagMap}
};

const journal = journalMeta as unknown as Journal;

function buildBundle(): EmbeddedMigration[] {
  return journal.entries
    .slice()
    .sort((a, b) => a.idx - b.idx)
    .map((e) => {
      const raw = SQL_BY_TAG[e.tag];
      if (raw === undefined) {
        // Caught by \`migrate-embedded-bundle.test.ts\` in CI long before
        // a binary ships.
        throw new Error(
          \`embedded.ts is out of sync with meta/_journal.json: missing SQL for tag '\${e.tag}'\`,
        );
      }
      const statements = raw
        .split("--> statement-breakpoint")
        .map((s) => s.trim())
        .filter((s) => s.length > 0);
      const hash = createHash("sha256").update(raw).digest("hex");
      return { idx: e.idx, tag: e.tag, when: e.when, hash, statements };
    });
}

export const EMBEDDED_MIGRATIONS: readonly EmbeddedMigration[] = buildBundle();
export const EMBEDDED_JOURNAL: Journal = journal;
`;

  await fs.writeFile(OUT_PATH, out, "utf8");
  process.stdout.write(`wrote ${path.relative(REPO_ROOT, OUT_PATH)} (${entries.length} entries)\n`);
}

await main();
