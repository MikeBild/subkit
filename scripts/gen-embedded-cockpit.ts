import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const bundleDir = join(root, "assets", "cockpit");
const output = join(root, "apps", "engine", "src", "http", "cockpit-embedded.ts");

function walk(dir: string, found: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, found);
    else found.push(full);
  }
  return found;
}

function generate(): { content: string; count: number; hasShell: boolean } {
  let files: string[] = [];
  try {
    files = walk(bundleDir).sort();
  } catch {
    files = [];
  }
  const entries = files.map((file) => {
    const key = relative(bundleDir, file).split(sep).join("/");
    return `  ${JSON.stringify(key)}: ${JSON.stringify(readFileSync(file).toString("base64"))},`;
  });
  return {
    content: `// GENERATED by scripts/gen-embedded-cockpit.ts — do not edit.\nexport const EMBEDDED_COCKPIT: Record<string, string> = {\n${entries.join("\n")}\n};\nexport const EMBEDDED_COCKPIT_FILES = ${files.length};\n`,
    count: files.length,
    hasShell: files.includes(join(bundleDir, "index.html")),
  };
}

const generated = generate();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(output, "utf8");
  } catch {
    current = "";
  }
  if (current !== generated.content) {
    console.error("cockpit embed is stale — run bun run build:cockpit");
    process.exit(1);
  }
  console.log("cockpit embed is current");
} else if (!generated.hasShell) {
  console.error(`cockpit bundle has no index.html in ${bundleDir} — run bun run build:cockpit`);
  process.exit(1);
} else {
  writeFileSync(output, generated.content);
  console.log(`embedded ${generated.count} cockpit files`);
}
