#!/usr/bin/env bun
// Emit a boilerplate REST route file under apps/engine/src/http/routes/
// plus a stub integration test. Reuses the shared spine in
// apps/engine/src/api/common-schemas.ts so the new route inherits the
// unified error + pagination envelope by default.
//
// Usage:
//   bun run scripts/scaffold/route.ts <slug>
//
// Example:
//   bun run scripts/scaffold/route.ts widgets
// produces:
//   apps/engine/src/http/routes/widgets.ts
//   apps/engine/src/http/tests/widgets.test.ts   (empty stub)
//
// After the file is written you still need to:
//   1. Register the exported `registerWidgetsRoutes(app)` in
//      apps/engine/src/http/server.ts.
//   2. Fill in the CRUD shape and the RBAC permission string.

import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..", "..");

function usage(): never {
  console.error("usage: bun run scripts/scaffold/route.ts <slug>");
  process.exit(2);
}

const slug = process.argv[2];
if (!slug || !/^[a-z][a-z0-9-]*$/.test(slug)) usage();

const pascal = slug
  .split("-")
  .map((s) => s[0]!.toUpperCase() + s.slice(1))
  .join("");

const routeFile = path.join(ROOT, "apps/engine/src/http/routes", `${slug}.ts`);
const testFile = path.join(ROOT, "apps/engine/src/http/tests", `${slug}.test.ts`);

if (existsSync(routeFile)) {
  console.error(`refusing to overwrite ${routeFile}`);
  process.exit(1);
}

const routeSource = `// ${pascal} HTTP surface.
//
// Auto-generated by scripts/scaffold/route.ts. Fill in the actual shape
// and permission string, then register in apps/engine/src/http/server.ts.

import { createRoute, type OpenAPIHono, z } from "@hono/zod-openapi";
import { ErrorSchema, IdParam, paginatedResponse } from "../../api/common-schemas.ts";
import { requireAuth } from "../middleware/auth.ts";
import { requirePermission } from "../middleware/require-permission.ts";
import type { AppEnv } from "../openapi.ts";

const ${pascal}Schema = z
  .object({
    id: z.string().uuid(),
    tenant_id: z.string().uuid(),
    created_at: z.string(),
  })
  .openapi("${pascal}");

const List${pascal}Response = paginatedResponse(${pascal}Schema, "${pascal}ListResponse");

const listRoute = createRoute({
  method: "get",
  path: "/v1/${slug}",
  tags: ["${slug}"],
  summary: "List ${slug}",
  security: [{ bearerAuth: [] }],
  responses: {
    200: {
      description: "OK",
      content: { "application/json": { schema: List${pascal}Response } },
    },
  },
});

const getRoute = createRoute({
  method: "get",
  path: "/v1/${slug}/{id}",
  tags: ["${slug}"],
  summary: "Fetch a ${slug.replace(/s$/, "")}",
  security: [{ bearerAuth: [] }],
  request: { params: IdParam },
  responses: {
    200: { description: "OK", content: { "application/json": { schema: ${pascal}Schema } } },
    404: { description: "Not found", content: { "application/json": { schema: ErrorSchema } } },
  },
});

export function register${pascal}Routes(app: OpenAPIHono<AppEnv>): void {
  // Collection-level gate (no resource id). For per-id routes add a second
  // \`app.use("/v1/${slug}/:id", ...)\` that passes \`() => ({ type: "${slug.replace(/s$/, "")}", id })\`
  // — see apps/engine/src/http/routes/executions.ts for the pattern.
  app.use("/v1/${slug}", requirePermission("${slug}:read"));
  app.use("/v1/${slug}/*", requirePermission("${slug}:read"));

  app.openapi(listRoute, async (c) => {
    const _principal = requireAuth(c);
    // TODO: query DB, scoped to principal.tenant_id.
    return c.json({ items: [] }, 200);
  });

  app.openapi(getRoute, async (c) => {
    const _principal = requireAuth(c);
    const { id: _id } = c.req.valid("param");
    // TODO: fetch + 404 if not found.
    return c.json({ id: _id, tenant_id: _principal.tenant_id, created_at: new Date().toISOString() }, 200);
  });
}
`;

const testSource = `// Integration tests for /v1/${slug} routes. Auto-generated stub.

import { describe, test } from "bun:test";

describe("${slug} routes", () => {
  test.todo("GET /v1/${slug} returns a paginated list", () => {});
  test.todo("GET /v1/${slug}/{id} returns 404 for unknown id", () => {});
});
`;

writeFileSync(routeFile, routeSource);
if (!existsSync(testFile)) writeFileSync(testFile, testSource);

console.log(`wrote ${path.relative(ROOT, routeFile)}`);
console.log(`wrote ${path.relative(ROOT, testFile)}`);
console.log("\nnext steps:");
console.log(`  1. register register${pascal}Routes(app) in apps/engine/src/http/server.ts`);
console.log(`  2. add the RBAC permission strings to apps/engine/src/rbac/permissions.ts`);
console.log(`  3. fill in the TODO queries in ${path.relative(ROOT, routeFile)}`);
console.log(`  4. bun run typecheck && bun run test:integration`);
