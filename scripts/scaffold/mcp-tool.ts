#!/usr/bin/env bun
// Emit a boilerplate MCP tool capability under
// apps/engine/src/mcp/capabilities/ + a stub unit test. Reuses the
// shared error adapter in apps/engine/src/mcp/error-adapter.ts so the
// new tool surfaces HttpError codes consistently with every other
// capability.
//
// Usage:
//   bun run scripts/scaffold/mcp-tool.ts <name>
//
// Example:
//   bun run scripts/scaffold/mcp-tool.ts widgets
// produces:
//   apps/engine/src/mcp/capabilities/widgets.ts
//   apps/engine/src/mcp/tests/widgets.test.ts
//
// After the file is written you still need to:
//   1. Register the exported `registerWidgetsTools(...)` in
//      apps/engine/src/mcp/server.ts (or the capabilities aggregator).
//   2. Gate each tool behind the correct RBAC permission via `can(...)`.
//   3. Replace the TODO with the real work.

import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..", "..");

function usage(): never {
  console.error("usage: bun run scripts/scaffold/mcp-tool.ts <name>");
  process.exit(2);
}

const slug = process.argv[2];
if (!slug || !/^[a-z][a-z0-9-]*$/.test(slug)) usage();

const pascal = slug
  .split("-")
  .map((s) => s[0]!.toUpperCase() + s.slice(1))
  .join("");
const toolName = slug.replace(/-/g, "_");

const capFile = path.join(ROOT, "apps/engine/src/mcp/capabilities", `${slug}.ts`);
const testFile = path.join(ROOT, "apps/engine/src/mcp/tests", `${slug}.test.ts`);

if (existsSync(capFile)) {
  console.error(`refusing to overwrite ${capFile}`);
  process.exit(1);
}

// Uses the actual MCP SDK surface:
//   server.setRequestHandler(ListToolsRequestSchema, ...)
//   server.setRequestHandler(CallToolRequestSchema, ...)
// The CallTool handler dispatches by request.params.name === "<toolName>"
// since MCP registers tools behind a single call handler.

const capSource = `// ${pascal} MCP tool capability.
//
// Auto-generated by scripts/scaffold/mcp-tool.ts. Fill in the real work,
// register in apps/engine/src/mcp/server.ts, and add a permission gate
// via \`can(...)\`.

import type { Server } from "@modelcontextprotocol/sdk/server/index.js";
import {
  CallToolRequestSchema,
  ListToolsRequestSchema,
  type Tool,
} from "@modelcontextprotocol/sdk/types.js";
import type { ResolvedPrincipal } from "../../auth/types.ts";
import type { Db } from "../../db/client.ts";
import { toMcpErrorText } from "../error-adapter.ts";

const TOOL_NAME = "${toolName}";

const ${pascal}Tool: Tool = {
  name: TOOL_NAME,
  description: "TODO: one-sentence description of what the ${toolName} tool does.",
  inputSchema: { type: "object", properties: {} },
};

export interface Register${pascal}ToolsParams {
  server: Server;
  db: Db;
  principal: ResolvedPrincipal;
}

export function register${pascal}Tools({
  server,
  db: _db,
  principal: _principal,
}: Register${pascal}ToolsParams): void {
  server.registerCapabilities({ tools: { listChanged: false } });

  server.setRequestHandler(ListToolsRequestSchema, async () => ({
    tools: [${pascal}Tool],
  }));

  server.setRequestHandler(CallToolRequestSchema, async (request) => {
    if (request.params.name !== TOOL_NAME) {
      return {
        isError: true,
        content: [{ type: "text" as const, text: \`unknown tool: \${request.params.name}\` }],
      };
    }
    try {
      // TODO: implement using _db + _principal (RBAC via \`can(_principal, ...)\`).
      const result = { ok: true };
      return {
        content: [{ type: "text" as const, text: JSON.stringify(result) }],
      };
    } catch (err) {
      return {
        isError: true,
        content: [{ type: "text" as const, text: toMcpErrorText(err) }],
      };
    }
  });
}
`;

const testSource = `// Integration tests for the ${slug} MCP tool. Auto-generated stub.

import { describe, test } from "bun:test";

describe("${slug} MCP tool", () => {
  test.todo("tools/list returns the ${toolName} tool", () => {});
  test.todo("tools/call ${toolName} returns ok: true on the happy path", () => {});
  test.todo("tools/call ${toolName} surfaces an HttpError via toMcpErrorText on failure", () => {});
});
`;

writeFileSync(capFile, capSource);
if (!existsSync(testFile)) writeFileSync(testFile, testSource);

console.log(`wrote ${path.relative(ROOT, capFile)}`);
console.log(`wrote ${path.relative(ROOT, testFile)}`);
console.log("\nnext steps:");
console.log(`  1. register register${pascal}Tools(...) in apps/engine/src/mcp/server.ts`);
console.log("  2. add an RBAC gate via `can(...)` inside the CallTool handler");
console.log("  3. replace the TODO with the real implementation");
console.log("  4. bun run typecheck && bun run test:integration");
